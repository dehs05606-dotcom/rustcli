"""INTROSPECT — the runtime describing itself, and docs that cannot drift.

Two problems, one module.

The first: everything this agent enforces is decided by code that is not
visible from outside it. Which tools exist, what each may do, which
policy stages run and in what order, what the contracts currently promise,
how often any of it fired. Answering those from the source means reading
six files and trusting that you read them correctly. So `describe()`
returns the whole picture as plain data, and the CLI prints it -- headless,
no session, no API key, no TUI.

The second: documentation drifts. A tool gets an argument, the README does
not. Six months later the docs are confidently wrong, which is worse than
having none, because people believe them. So the tool reference is
*generated* from the registry, and `docs_current()` compares the generated
text with what is on disk. `run-checks.sh` fails when they differ, which
makes the stale state unreachable rather than merely discouraged.

    python -m fullagent.introspect              everything, as text
    python -m fullagent.introspect tools --json machine-readable
    python -m fullagent.introspect --write-docs regenerate docs/TOOLS.md
    python -m fullagent.introspect --check-docs fail if they are stale
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .contractmanifest import LOCK_NAME, manifest, read_lock
from .policypipeline import DEFAULT_PIPELINE
from .recovery import PLAYBOOKS, STRATEGIES
from .toolcontract import ERROR_CODES, RETRYABLE, build_contracts
from .toolpolicy import (ALL_CAPABILITIES, ROLES, TOOL_CAPABILITIES,
                         ToolPolicy)

DOCS_PATH = Path("docs") / "TOOLS.md"
GENERATED_BANNER = (
    "<!-- Generated by `python -m fullagent.introspect --write-docs`. "
    "Do not edit by hand: run-checks.sh fails when this file and the "
    "registry disagree. -->")

SECTIONS = ("tools", "policy", "contracts", "recovery", "metrics",
            "telemetry")


def _tool_section(registry: dict) -> dict:
    contracts = build_contracts(registry)
    out = []
    for name in sorted(contracts):
        c = contracts[name]
        out.append({
            "name": name,
            "description": c.description,
            "version": c.version,
            "permission": sorted(c.permission),
            "idempotency": c.idempotency,
            "timeout_seconds": c.timeout_seconds,
            "needs_approval": c.needs_approval,
            "destructive": c.destructive,
            "outward_facing": c.outward_facing,
            "errors": sorted(set(c.errors)),
            "retry": c.retry.to_dict(),
            "arguments": _arguments_of(c.input_schema),
        })
    return {"count": len(out), "tools": out}


def _arguments_of(schema: dict) -> list[dict]:
    props = (schema or {}).get("properties") or {}
    required = set((schema or {}).get("required") or ())
    return [{"name": key,
             "type": str(spec.get("type", "any")),
             "required": key in required,
             "description": str(spec.get("description", ""))}
            for key, spec in sorted(props.items())]


def _policy_section(policy: ToolPolicy | None) -> dict:
    out: dict[str, Any] = {
        "stages": list(DEFAULT_PIPELINE.names()),
        "capabilities": list(ALL_CAPABILITIES),
        "roles": {name: {"capabilities": sorted(role.capabilities),
                         "ask": sorted(role.ask_capabilities),
                         "allow_destructive_commands":
                             role.allow_destructive_commands,
                         "ceilings": dict(role.ceilings),
                         "allowed_hosts": list(role.allowed_hosts)}
                  for name, role in sorted(ROLES.items())},
        "manifest": {name: sorted(caps)
                     for name, caps in sorted(TOOL_CAPABILITIES.items())},
    }
    if policy is not None:
        out["active"] = {"role": policy.role.name,
                         "roots": list(policy.roots),
                         "calls_so_far": dict(policy.counts)}
    return out


def _contract_section(registry: dict, root: Path) -> dict:
    current = manifest(build_contracts(registry))
    locked = read_lock(root / LOCK_NAME)
    return {"contract_version": current["contract_version"],
            "digest": current["digest"],
            "locked_digest": (locked or {}).get("digest", ""),
            "in_sync": bool(locked) and
            locked.get("digest") == current["digest"],
            "tools": {name: entry["digest"]
                      for name, entry in current["tools"].items()}}


def _recovery_section() -> dict:
    return {"strategies": list(STRATEGIES),
            "codes": {code: {"retryable": RETRYABLE[code],
                             **PLAYBOOKS[code].to_dict()}
                      for code in ERROR_CODES}}


def _metrics_section(dispatcher) -> dict:
    if dispatcher is None:
        return {"available": False}
    m = dispatcher.metrics
    return {"available": True,
            "calls": dict(m.calls), "failures": dict(m.failures),
            "errors_by_code": dict(m.errors_by_code),
            "retries": m.retries, "denials": m.denials,
            "approvals_requested": m.approvals_requested,
            "approvals_refused": m.approvals_refused,
            "registered": len(dispatcher.contracts),
            "available_tools": list(dispatcher.negotiate().available)}


def _telemetry_section(telemetry, prompt: str = "main") -> dict:
    if telemetry is None:
        return {"available": False}
    return {"available": True,
            "prompt": prompt,
            "scorecards": [c.to_dict() for c in telemetry.scorecards(prompt)],
            "drifting": [c.model for c in telemetry.drifting(prompt)],
            "proposals": [p.to_dict() for p in telemetry.proposals]}


def describe(registry: dict | None = None, policy: ToolPolicy | None = None,
             dispatcher=None, telemetry=None, root: str | Path = ".",
             sections: tuple[str, ...] = SECTIONS) -> dict:
    """The whole runtime as plain data. Reads nothing it cannot see."""
    if registry is None:
        from .tools import build_registry
        registry = build_registry()
    root = Path(root)
    out: dict[str, Any] = {}
    if "tools" in sections:
        out["tools"] = _tool_section(registry)
    if "policy" in sections:
        out["policy"] = _policy_section(policy)
    if "contracts" in sections:
        out["contracts"] = _contract_section(registry, root)
    if "recovery" in sections:
        out["recovery"] = _recovery_section()
    if "metrics" in sections:
        out["metrics"] = _metrics_section(dispatcher)
    if "telemetry" in sections:
        out["telemetry"] = _telemetry_section(telemetry)
    return out


def format_description(data: dict) -> str:
    """The same picture, for a person reading a terminal."""
    lines: list[str] = []
    tools = data.get("tools")
    if tools:
        lines.append(f"TOOLS — {tools['count']} registered")
        for t in tools["tools"]:
            flags = []
            if t["needs_approval"]:
                flags.append("approval")
            if t["destructive"]:
                flags.append("destructive")
            if t["outward_facing"]:
                flags.append("outward")
            tail = f"  [{', '.join(flags)}]" if flags else ""
            lines.append(f"  {t['name']:<18} {', '.join(t['permission']) or '-':<28}"
                         f" {t['idempotency']}{tail}")
    policy = data.get("policy")
    if policy:
        lines.append("")
        lines.append("POLICY — stages in order")
        lines.append("  " + " -> ".join(policy["stages"]))
        active = policy.get("active")
        if active:
            lines.append(f"  active role '{active['role']}' "
                         f"rooted at {', '.join(active['roots'])}")
        for name, role in policy["roles"].items():
            ask = f" (asks: {', '.join(role['ask'])})" if role["ask"] else ""
            lines.append(f"  {name:<10} {', '.join(role['capabilities'])}{ask}")
    contracts = data.get("contracts")
    if contracts:
        lines.append("")
        state = "in sync" if contracts["in_sync"] else "OUT OF SYNC with the lock file"
        lines.append(f"CONTRACTS — v{contracts['contract_version']}, "
                     f"digest {contracts['digest']} ({state})")
    recovery = data.get("recovery")
    if recovery:
        lines.append("")
        lines.append(f"RECOVERY — {len(recovery['codes'])} codes")
        for code, book in recovery["codes"].items():
            retry = "retryable" if book["retryable"] else "final"
            lines.append(f"  {code:<14} {book['strategy']:<11} {retry}")
    metrics = data.get("metrics")
    if metrics and metrics.get("available"):
        lines.append("")
        total = sum(metrics["calls"].values())
        lines.append(f"METRICS — {total} call(s), "
                     f"{sum(metrics['failures'].values())} failed, "
                     f"{metrics['retries']} retried, "
                     f"{metrics['denials']} denied")
    telemetry = data.get("telemetry")
    if telemetry and telemetry.get("available"):
        lines.append("")
        lines.append(f"TELEMETRY — {len(telemetry['scorecards'])} model(s)")
        for card in telemetry["scorecards"]:
            score = card["score"]
            lines.append(f"  {card['model']:<18} {card['grade']:<9} "
                         f"{score if score is not None else '-'}")
    return "\n".join(lines)


