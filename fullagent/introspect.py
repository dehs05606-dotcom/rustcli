def _cli(argv: list[str]) -> int:
    from .tools import build_registry

    root = Path(__file__).resolve().parent.parent
    registry = build_registry()

    if "--write-docs" in argv:
        target = write_tool_docs(root / DOCS_PATH, registry)
        print(f"wrote {target.relative_to(root)} — {len(registry)} tools")
        return 0
    if "--check-docs" in argv:
        ok, why = docs_current(root / DOCS_PATH, registry)
        print(("DOCS CURRENT — " if ok else "DOCS STALE — ") + why)
        return 0 if ok else 1

    wanted = tuple(a for a in argv if not a.startswith("-")) or SECTIONS
    unknown = [w for w in wanted if w not in SECTIONS]
    if unknown:
        print(f"unknown section(s): {', '.join(unknown)}; "
              f"choose from {', '.join(SECTIONS)}")
        return 2
    policy = ToolPolicy("developer", roots=(str(root),))
    data = describe(registry, policy, root=root, sections=wanted)
    print(json.dumps(data, indent=2, sort_keys=True) if "--json" in argv
          else format_description(data))
    return 0


if __name__ == "__main__":
    import sys

    if len(sys.argv) > 1:
        raise SystemExit(_cli(sys.argv[1:]))

    # ------------------------------------------------------------------
    # Self-test
    # ------------------------------------------------------------------
    import tempfile

    from .dispatch import Dispatcher
    from .telemetry import Telemetry
    from .tools import build_registry

    root = Path(__file__).resolve().parent.parent
    registry = build_registry()
    work = Path(tempfile.mkdtemp(prefix="fa-introspect-"))

    # --- every section is present and plain data -----------------------
    data = describe(registry, root=root)
    assert set(data) == set(SECTIONS), sorted(data)
    json.dumps(data)   # raises if anything in here is not serialisable

    assert data["tools"]["count"] == len(registry)
    names = {t["name"] for t in data["tools"]["tools"]}
    assert names == set(registry), names ^ set(registry)

    # --- the described policy is the one that actually runs ------------
    assert data["policy"]["stages"] == list(DEFAULT_PIPELINE.names())
    assert set(data["policy"]["roles"]) == set(ROLES)
    for name, role in ROLES.items():
        assert data["policy"]["roles"][name]["capabilities"] == \
            sorted(role.capabilities)

    policy = ToolPolicy("readonly", roots=(str(work),))
    scoped = describe(registry, policy, root=root, sections=("policy",))
    assert scoped["policy"]["active"]["role"] == "readonly"
    assert set(scoped) == {"policy"}, "a section filter must filter"

    # --- contracts report whether they match the lock file -------------
    assert data["contracts"]["in_sync"], \
        "the checked-in lock file disagrees with the registry"
    assert len(data["contracts"]["tools"]) == len(registry)

    # --- recovery describes every code in the taxonomy -----------------
    assert set(data["recovery"]["codes"]) == set(ERROR_CODES)
    for code, book in data["recovery"]["codes"].items():
        assert book["strategy"] in STRATEGIES
        assert book["retryable"] == RETRYABLE[code]

    # --- metrics and telemetry appear once something has run -----------
    assert data["metrics"] == {"available": False}
    dispatcher = Dispatcher(policy=ToolPolicy("developer", roots=(str(work),)),
                            approve=lambda c, a: True)
    dispatcher.register_registry(registry, build_contracts(registry))
    dispatcher.call("list_dir", {"path": str(work)})
    live = describe(registry, dispatcher=dispatcher, root=root,
                    sections=("metrics",))
    assert live["metrics"]["available"] and live["metrics"]["calls"]["list_dir"] == 1

    tel = Telemetry()
    for _ in range(12):
        tel.observe("a-model", 0.95)
    with_models = describe(registry, telemetry=tel, root=root,
                           sections=("telemetry",))
    assert with_models["telemetry"]["scorecards"][0]["model"] == "a-model"

    # --- the text rendering says something about each part -------------
    text = format_description(describe(registry, policy, dispatcher, tel,
                                       root=root))
    for heading in ("TOOLS", "POLICY", "CONTRACTS", "RECOVERY", "METRICS",
                    "TELEMETRY"):
        assert heading in text, heading

    # --- generated docs describe every tool, and detect staleness ------
    rendered = render_tool_docs(registry)
    for name in registry:
        assert f"## `{name}`" in rendered, f"{name} is missing from the docs"
    assert GENERATED_BANNER in rendered
    assert render_tool_docs(registry) == rendered, \
        "doc generation is not deterministic"

    target = work / "TOOLS.md"
    ok, why = docs_current(target, registry)
    assert not ok and "does not exist" in why, why

    write_tool_docs(target, registry)
    ok, why = docs_current(target, registry)
    assert ok, why

    target.write_text(rendered + "\nsomeone edited this by hand\n")
    ok, why = docs_current(target, registry)
    assert not ok and "stale" in why, why

    # a tool added to the registry makes the docs stale immediately
    from .tools import Tool
    extra = dict(registry)
    extra["brand_new_tool"] = Tool(
        "brand_new_tool", "invented for this test",
        {"type": "object", "properties": {}}, lambda **kw: "")
    write_tool_docs(target, registry)
    ok, why = docs_current(target, extra)
    assert not ok, "a new tool must make the generated docs stale"

    print(format_description(describe(registry, policy, root=root,
                                      sections=("policy", "contracts"))))
    print(f"INTROSPECT SELF-TEST PASS — {len(registry)} tools, "
          f"{len(SECTIONS)} sections, {len(rendered.splitlines())} doc lines")
