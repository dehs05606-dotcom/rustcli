def render_tool_docs(registry: dict | None = None) -> str:
    """The tool reference, generated from the registry it documents."""
    if registry is None:
        from .tools import build_registry
        registry = build_registry()
    contracts = build_contracts(registry)
    lines = ["# Tool reference", "", GENERATED_BANNER, "",
             f"{len(contracts)} tools. Each one's schema, permission class "
             f"and error set is derived from its registry entry in",
             "`fullagent/tools.py`, so this page cannot describe a tool "
             "differently from the way it actually behaves.", ""]

    lines.append("| Tool | Needs | Repeatable | Approval | Errors |")
    lines.append("|---|---|---|---|---|")
    for name in sorted(contracts):
        c = contracts[name]
        lines.append(
            f"| `{name}` | {', '.join(sorted(c.permission)) or '—'} "
            f"| {c.idempotency} "
            f"| {'yes' if c.needs_approval else 'no'} "
            f"| {len(set(c.errors))} |")
    lines.append("")

    for name in sorted(contracts):
        c = contracts[name]
        lines.append(f"## `{name}`")
        lines.append("")
        lines.append(c.description)
        lines.append("")
        args = _arguments_of(c.input_schema)
        if args:
            lines.append("| Argument | Type | Required | Meaning |")
            lines.append("|---|---|---|---|")
            for a in args:
                lines.append(
                    f"| `{a['name']}` | {a['type']} "
                    f"| {'yes' if a['required'] else 'no'} "
                    f"| {a['description'] or '—'} |")
        else:
            lines.append("Takes no arguments.")
        lines.append("")
        facts = [f"**Needs:** {', '.join(sorted(c.permission)) or 'nothing'}",
                 f"**Repeatable:** {c.idempotency}",
                 f"**Timeout:** {c.timeout_seconds:g}s",
                 f"**Approval:** {'required' if c.needs_approval else 'not required'}"]
        if c.retry.max_attempts > 1:
            facts.append(f"**Retry:** up to {c.retry.max_attempts} attempts "
                         f"on {', '.join(c.retry.codes)}")
        lines.append(" · ".join(facts))
        lines.append("")
        lines.append(f"**Can fail with:** "
                     f"{', '.join(f'`{e}`' for e in sorted(set(c.errors)))}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def docs_current(path: str | Path | None = None,
                 registry: dict | None = None) -> tuple[bool, str]:
    """Is the generated reference on disk still what the registry says?"""
    target = Path(path) if path else DOCS_PATH
    rendered = render_tool_docs(registry)
    try:
        on_disk = target.read_text(encoding="utf-8")
    except OSError:
        return False, f"{target} does not exist"
    if on_disk == rendered:
        return True, f"{target} matches the registry"
    return False, (f"{target} is stale; regenerate it with "
                   f"`python -m fullagent.introspect --write-docs`")


def write_tool_docs(path: str | Path | None = None,
                    registry: dict | None = None) -> Path:
    target = Path(path) if path else DOCS_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_tool_docs(registry), encoding="utf-8")
    return target


